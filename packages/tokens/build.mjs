// Builds every @usezeno/tokens output from the JSON in src/tokens.
//
// Style Dictionary parses the token files, resolves references and names each
// token. This script then writes the outputs, because the stylesheet needs two
// resolved dictionaries (light and dark) in one file.
//
//   dist/css/tokens.css       custom properties on :root, light and dark
//   dist/css/tokens.css.d.ts  an empty module, so the stylesheet import typechecks
//   dist/index.js             tokens, light, dark and vars as ES module exports
//   dist/index.d.ts           their types
//   dist/tokens.json          resolved values with no CSS formatting, for other platforms

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

const root = dirname(fileURLToPath(import.meta.url));
const PREFIX = 'zeno';
const THEMES = ['light', 'dark'];
const THEME_GROUPS = new Set(['color', 'shadow']);

/** Resolves one theme: the base tokens plus that theme's colours and shadows. */
async function resolveTheme(theme) {
  const sd = new StyleDictionary({
    source: [
      resolve(root, 'src/tokens/base/*.json'),
      resolve(root, `src/tokens/theme/${theme}.json`),
    ],
    log: { warnings: 'error', verbosity: 'default' },
    platforms: {
      css: { prefix: PREFIX, transforms: ['name/kebab'] },
    },
  });
  const { allTokens } = await sd.getPlatformTokens('css');
  return allTokens.map(token => ({
    name: token.name,
    path: token.path,
    type: token.$type,
    value: token.$value,
    original: token.original.$value,
    description: token.$description,
  }));
}

function cssValue(token) {
  const { type, value, original } = token;
  // A token that only points at another token stays a reference in CSS, so
  // overriding a palette step re-themes everything built on it.
  const reference =
    typeof original === 'string' && /^\{[^{}]+\}$/.test(original)
      ? original.slice(1, -1).split('.')
      : undefined;
  if (reference) {
    return `var(--${cssName(reference)})`;
  }
  if (type === 'fontFamily') {
    return value
      .map(name => (/^[A-Za-z-]+$/.test(name) ? name : `'${name}'`))
      .join(', ');
  }
  if (type === 'cubicBezier') {
    return `cubic-bezier(${value.join(', ')})`;
  }
  return String(value);
}

function kebab(segment) {
  return segment.replace(/([a-z])([A-Z])/g, '$1-$2').toLowerCase();
}

function cssName(path) {
  return [PREFIX, ...path.map(kebab)].join('-');
}

function declarations(tokens, indent) {
  return tokens
    .map(token => `${indent}--${cssName(token.path)}: ${cssValue(token)};`)
    .join('\n');
}

function stylesheet(resolved) {
  const isThemed = token => THEME_GROUPS.has(token.path[0]);
  const base = resolved.light.filter(token => !isThemed(token));
  const light = resolved.light.filter(isThemed);
  const dark = resolved.dark.filter(isThemed);

  return `/**
 * Zeno design tokens. Generated by build.mjs from src/tokens. Do not edit.
 *
 * Light is the default. Dark applies when the operating system asks for it,
 * unless an ancestor sets data-theme="light". data-theme="dark" forces dark
 * on that element and everything inside it, and data-theme="light" forces
 * light the same way.
 */

:root {
${declarations(base, '  ')}
}

:root,
[data-theme='light'] {
  color-scheme: light;
${declarations(light, '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${declarations(dark, '    ')}
  }
}

[data-theme='dark'] {
  color-scheme: dark;
${declarations(dark, '  ')}
}
`;
}

function nest(tokens, leaf) {
  const tree = {};
  for (const token of tokens) {
    let node = tree;
    token.path.slice(0, -1).forEach(key => {
      node[key] ??= {};
      node = node[key];
    });
    node[token.path.at(-1)] = leaf(token);
  }
  return tree;
}

/** Numbers stay numbers. Everything else is the string CSS would use. */
function jsValue(token) {
  if (typeof token.value === 'number') {
    return token.value;
  }
  return cssValue({ ...token, original: undefined });
}

function typeOf(value, indent = '') {
  if (typeof value !== 'object') {
    return typeof value;
  }
  const inner = `${indent}  `;
  const lines = Object.entries(value).map(
    ([key, child]) =>
      `${inner}readonly ${JSON.stringify(key)}: ${typeOf(child, inner)};`
  );
  return `{\n${lines.join('\n')}\n${indent}}`;
}

function moduleFiles(resolved) {
  const isThemed = token => THEME_GROUPS.has(token.path[0]);
  const exports = {
    tokens: nest(
      resolved.light.filter(token => !isThemed(token)),
      jsValue
    ),
    light: nest(resolved.light.filter(isThemed), jsValue),
    dark: nest(resolved.dark.filter(isThemed), jsValue),
    vars: nest(resolved.light, token => `var(--${cssName(token.path)})`),
  };
  const docs = {
    tokens: 'Tokens that are the same in every theme.',
    light: 'Colours and shadows of the light theme, resolved.',
    dark: 'Colours and shadows of the dark theme, resolved.',
    vars: 'Every token as a `var(--zeno-…)` reference, for styles written in JavaScript.',
  };
  const header =
    '// Zeno design tokens. Generated by build.mjs from src/tokens. Do not edit.\n';
  const js = Object.entries(exports)
    .map(
      ([name, value]) =>
        `/** ${docs[name]} */\nexport const ${name} = ${JSON.stringify(value, null, 2)};\n`
    )
    .join('\n');
  const dts = Object.entries(exports)
    .map(
      ([name, value]) =>
        `/** ${docs[name]} */\nexport declare const ${name}: ${typeOf(value)};\n`
    )
    .join('\n');
  return { js: header + '\n' + js, dts: header + '\n' + dts };
}

function rawJson(resolved) {
  const isThemed = token => THEME_GROUPS.has(token.path[0]);
  const leaf = token => ({ type: token.type, value: token.value });
  return {
    base: nest(
      resolved.light.filter(token => !isThemed(token)),
      leaf
    ),
    light: nest(resolved.light.filter(isThemed), leaf),
    dark: nest(resolved.dark.filter(isThemed), leaf),
  };
}

function assertSameShape(resolved) {
  const names = theme =>
    resolved[theme]
      .map(token => token.path.join('.'))
      .sort()
      .join('\n');
  const [first, ...rest] = THEMES;
  for (const theme of rest) {
    if (names(theme) !== names(first)) {
      const a = new Set(names(first).split('\n'));
      const b = new Set(names(theme).split('\n'));
      const missing = [...a].filter(name => !b.has(name));
      const extra = [...b].filter(name => !a.has(name));
      throw new Error(
        `Theme "${theme}" does not define the same tokens as "${first}". ` +
          `Missing: ${missing.join(', ') || 'none'}. Extra: ${extra.join(', ') || 'none'}.`
      );
    }
  }
}

const resolved = {};
for (const theme of THEMES) {
  resolved[theme] = await resolveTheme(theme);
}
assertSameShape(resolved);

const out = resolve(root, 'dist');
await mkdir(resolve(out, 'css'), { recursive: true });
const { js, dts } = moduleFiles(resolved);
await writeFile(resolve(out, 'css/tokens.css'), stylesheet(resolved));
// Lets TypeScript resolve `import '@usezeno/tokens/css'`.
await writeFile(resolve(out, 'css/tokens.css.d.ts'), 'export {};\n');
await writeFile(resolve(out, 'index.js'), js);
await writeFile(resolve(out, 'index.d.ts'), dts);
await writeFile(
  resolve(out, 'tokens.json'),
  JSON.stringify(rawJson(resolved), null, 2) + '\n'
);

console.log(
  `@usezeno/tokens: ${resolved.light.length} tokens, themes: ${THEMES.join(', ')}`
);
