// Writes the framework bindings from the custom-elements manifest that the
// @usezeno/core build produces:
//
//   packages/react/src/<element>.ts          a React component per element (@lit/react)
//   packages/react/src/index.ts              all of them
//   packages/core/src/elements/<element>.ts  an entry point per element
//   packages/vue/src/elements/generated.ts   template types for Vue
//   packages/svelte/src/elements.ts          markup types for Svelte
//
// Run `pnpm generate` after changing an element's properties or events.
// `pnpm generate:check` fails when a committed file is out of date.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const manifestPath = resolve(root, 'packages/core/dist/custom-elements.json');
const CORE = '@usezeno/core/web-components';
const HEADER = `// Generated by scripts/generate-bindings.mjs from the custom-elements manifest
// of @usezeno/core. Do not edit: change the element, then run \`pnpm generate\`.
`;

/** Type names that need no import. */
const GLOBAL_TYPES = new Set(['Array', 'CustomEvent', 'Date', 'Event', 'File']);

async function readElements() {
  let manifest;
  try {
    manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  } catch {
    throw new Error(
      `No manifest at ${relative(root, manifestPath)}. Build @usezeno/core first.`
    );
  }
  const elements = [];
  for (const module of manifest.modules) {
    for (const declaration of module.declarations ?? []) {
      if (!declaration.customElement || !declaration.tagName) continue;
      const fields = (declaration.members ?? []).filter(
        member =>
          member.kind === 'field' &&
          !member.privacy &&
          !member.static &&
          !member.readonly
      );
      elements.push({
        tagName: declaration.tagName,
        className: declaration.name,
        description: (declaration.description ?? '').trim(),
        properties: fields.map(field => field.name).sort(),
        // Attributes whose name differs from the property's, for frameworks
        // where markup is written with attribute names.
        attributes: fields
          .filter(field => field.attribute && field.attribute !== field.name)
          .map(field => ({ attribute: field.attribute, property: field.name }))
          .sort((a, b) => a.attribute.localeCompare(b.attribute)),
        events: (declaration.events ?? []).map(event => ({
          name: event.name,
          type: event.type?.text ?? 'CustomEvent',
          description: event.description ?? '',
        })),
      });
    }
  }
  return elements.sort((a, b) => a.tagName.localeCompare(b.tagName));
}

/** The types the event details mention, which the output has to import. */
function detailTypes(elements) {
  const names = new Set();
  for (const element of elements) {
    for (const event of element.events) {
      for (const [name] of event.type.matchAll(/\b[A-Z][A-Za-z0-9]*\b/g)) {
        if (!GLOBAL_TYPES.has(name)) names.add(name);
      }
    }
  }
  return [...names].sort();
}

function pascal(name) {
  return name.replace(/(^|-)([a-z])/g, (_, __, letter) => letter.toUpperCase());
}

function docComment(text, indent = '') {
  if (!text) return '';
  const lines = text.split('\n').map(line => `${indent} * ${line}`.trimEnd());
  return `${indent}/**\n${lines.join('\n')}\n${indent} */\n`;
}

function union(names) {
  return names.length > 0
    ? names.map(name => `'${name}'`).join(' | ')
    : 'never';
}

/** An object type with these members, or one with none. */
function members(lines) {
  return lines.length > 0
    ? `{\n${lines.join('\n')}\n    }`
    : 'Record<never, never>';
}

/** The short name of an element, used for its entry point: `zeno-button` is `button`. */
const shortName = element => element.tagName.replace(/^zeno-/, '');

function reactComponent(element) {
  const types = detailTypes([element]);
  const events = element.events.map(
    event =>
      `${docComment(event.description, '    ')}    on${pascal(event.name)}: '${event.name}' as EventName<${event.type}>,`
  );
  return `${HEADER}
import * as React from 'react';
import { createComponent${events.length > 0 ? ', type EventName' : ''} } from '@lit/react';
import { ${element.className} as ${element.className}Element } from '@usezeno/core/${shortName(element)}';
${types.length > 0 ? `import type { ${types.join(', ')} } from '${CORE}';\n` : ''}
export type { ${element.className}Element };

${docComment(element.description)}export const ${element.className} = /*#__PURE__*/ createComponent({
  tagName: '${element.tagName}',
  elementClass: ${element.className}Element,
  react: React,
  displayName: '${element.className}',${
    events.length > 0 ? `\n  events: {\n${events.join('\n')}\n  },` : ''
  }
});
`;
}

function react(elements) {
  return `${HEADER}
// Every element. An app that uses a few can import them one by one instead,
// from '@usezeno/react/button' and so on, and load only those.
${elements.map(e => `export { ${e.className}, type ${e.className}Element } from './${shortName(e)}.js';`).join('\n')}

// The types that event details and properties use.
export type * from '${CORE}';
`;
}

/** One entry point per element in @usezeno/core: '@usezeno/core/button'. */
function coreEntry(element) {
  return `${HEADER}
// Registers <${element.tagName}> and the elements it renders, and nothing else.
export * from '../components/lit/${shortName(element)}/${element.tagName}.js';
`;
}

function typeImports(elements) {
  const names = [...elements.map(e => e.className), ...detailTypes(elements)];
  return `import type { ${names.sort().join(', ')} } from '${CORE}';`;
}

function vue(elements) {
  const entries = elements.map(element => {
    const events = element.events.map(
      event =>
        `${docComment(event.description, '      ')}      on${pascal(event.name)}?: (event: ${event.type}) => void;`
    );
    return `${docComment(element.description, '  ')}  '${element.tagName}': ElementComponent<
    ${element.className},
    ${union(element.properties)},
    ${members(events)}
  >;`;
  });

  return `${HEADER}
import type { DefineComponent, HTMLAttributes } from 'vue';
${typeImports(elements)}

type ElementComponent<
  Element extends HTMLElement,
  Properties extends keyof Element,
  Events,
> = DefineComponent<
  Partial<Pick<Element, Properties>> &
    Events &
    Omit<HTMLAttributes, keyof Events | Properties>
>;

/** Every Zeno element, typed for use in a Vue template. */
export interface ZenoElements {
${entries.join('\n')}
}

declare module 'vue' {
  // eslint-disable-next-line @typescript-eslint/no-empty-object-type -- adds the elements to Vue's own list
  interface GlobalComponents extends ZenoElements {}
}
`;
}

function svelte(elements) {
  const entries = elements.map(element => {
    const attributes = element.attributes.map(
      ({ attribute, property }) =>
        `      '${attribute}'?: ${element.className}['${property}'];`
    );
    const events = element.events.map(
      event =>
        `${docComment(event.description, '      ')}      'on${event.name}'?: (event: ${event.type}) => void;`
    );
    const extra = [...attributes, ...events];
    return `${docComment(element.description, '  ')}  '${element.tagName}': ElementProps<
    ${element.className},
    ${union(element.properties)},
    ${members(extra)}
  >;`;
  });

  return `${HEADER}
import type { HTMLAttributes } from 'svelte/elements';
${typeImports(elements)}

type ElementProps<
  Element extends HTMLElement,
  Properties extends keyof Element,
  Extra,
> = Omit<HTMLAttributes<Element>, keyof Extra | Properties> &
  Partial<Pick<Element, Properties>> &
  Extra;

/** Every Zeno element, typed for use in Svelte markup. */
export interface ZenoElements {
${entries.join('\n')}
}

declare module 'svelte/elements' {
  // eslint-disable-next-line @typescript-eslint/no-empty-object-type -- adds the elements to Svelte's own list
  interface SvelteHTMLElements extends ZenoElements {}
}
`;
}

const elements = await readElements();
const outputs = {
  'packages/react/src/index.ts': react(elements),
  ...Object.fromEntries(
    elements.flatMap(element => [
      [`packages/react/src/${shortName(element)}.ts`, reactComponent(element)],
      [
        `packages/core/src/elements/${shortName(element)}.ts`,
        coreEntry(element),
      ],
    ])
  ),
  'packages/vue/src/elements/generated.ts': vue(elements),
  'packages/svelte/src/elements.ts': svelte(elements),
};
const check = process.argv.includes('--check');
const stale = [];

for (const [path, source] of Object.entries(outputs)) {
  const file = resolve(root, path);
  const options = await prettier.resolveConfig(file);
  const formatted = await prettier.format(source, {
    ...options,
    filepath: file,
  });
  const current = await readFile(file, 'utf8').catch(() => '');
  if (current === formatted) continue;
  if (check) {
    stale.push(path);
  } else {
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, formatted);
    console.log(`wrote ${path}`);
  }
}

if (stale.length > 0) {
  console.error(
    `Out of date: ${stale.join(', ')}. Run \`pnpm generate\` and commit the result.`
  );
  process.exit(1);
}
console.log(`bindings for ${elements.length} elements are up to date`);
